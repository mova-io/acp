"""Recovering an approval whose write was refused — without asking anyone to approve again.

THE PRODUCTION STATE (2026-09-17, `UTSW_Discharge_Summary.docx`). A 1.4.5 row sat `approved`
with `applied` NULL. The writer job had run and finished `done`, having refused the picture on
a crop safety check; the approved OCR transcript was kept, as the decision line promises. The
reviewer's card then told them:

    Approved, application pending. No active writer job is recorded; another approval is not
    needed.

Both halves of which misled. A job WAS recorded — it ran, and it refused for a stated reason
that was sitting in the decision log. And with no way to ask for the write again, "another
approval is not needed" left the only visible action being the one thing that would not help.

TWO THINGS ARE PINNED HERE, and they are the two halves of that dead end:

  * `automatic_review_queue.stalled_reason` now prefers the row's own `apply_outcome` — the
    refusal reason `store.list_hitl_queue` already parses onto it — so the card says what
    happened and what to do. This text reaches the user verbatim.
  * `store.retry_approved_write` re-runs the writer over content that is ALREADY approved. It
    creates no approval, records no decision on the row, clears nothing, marks nothing applied
    or verified, and enqueues exactly the payload a reviewer's own approval enqueues — so every
    downstream guard runs unchanged and a genuine refusal refuses again.

The value in this scan came from OCR, not a model (`ai_calls` was empty for that run), so
nothing asserted here may describe it as AI-generated.
"""
from __future__ import annotations

import json

import pytest

from apply_outcome import COULD_NOT_VERIFY, NOTHING_WRITTEN, STILL_FAILING
from automatic_review_queue import stalled_reason

CROP_REASON = ('The image is cropped in Word. Review a transcription of the visible crop and '
               'confirm no useful diagram content would be lost before replacing it. The '
               'original image is kept unchanged.')

SID = 'recovery-scan'
FILE = 'UTSW_Discharge_Summary.docx'


# ── the sentence the user reads ───────────────────────────────────────────────────────────

def test_a_refused_write_explains_itself_instead_of_denying_the_job_existed():
    row = {'status': 'approved', 'applied': None, 'rule_id': '1.4.5',
           'apply_outcome': {'outcome': NOTHING_WRITTEN, 'criteria': ['1.4.5'],
                             'reason': CROP_REASON}}
    reason = stalled_reason(row)
    # The refusal's own words reach the user, unaltered.
    assert CROP_REASON in reason
    # The two false/dead-end claims are gone.
    assert 'No active writer job is recorded' not in reason
    assert 'application pending' not in reason
    # And the user is told the approval survives and what to do next.
    assert 'approval still stands' in reason
    assert 'retry saving it' in reason
    assert 'not be asked to approve it again' in reason


def test_no_reason_string_claims_the_value_came_from_ai():
    """`ai_calls` was empty for this run: the transcript is OCR. Nothing may say otherwise."""
    outcomes = [{'outcome': NOTHING_WRITTEN, 'reason': CROP_REASON},
                {'outcome': COULD_NOT_VERIFY, 'reason': 'scan status error'},
                {'outcome': STILL_FAILING, 'reason': ''}, {}]
    for outcome in outcomes:
        for applied in (None, 1):
            text = stalled_reason({'status': 'approved', 'applied': applied,
                                   'apply_outcome': outcome}).lower()
            assert not any(word in text for word in
                           (' ai ', 'ai-', 'artificial intelligence', 'model-written',
                            'generated by', 'ai suggestion')), text


def test_a_written_but_unverified_change_is_not_described_as_unsaved():
    reason = stalled_reason({'status': 'approved', 'applied': None,
                             'apply_outcome': {'outcome': COULD_NOT_VERIFY,
                                               'reason': "scan status 'error', 1 rule(s) skipped"}})
    assert 'was written' in reason
    assert 'no further approval is needed' in reason
    assert "scan status 'error'" in reason


def test_the_fallback_no_longer_claims_no_job_was_ever_recorded():
    """The honest weaker claim: none is running NOW — true whether one finished or none existed."""
    unsaved = stalled_reason({'status': 'approved', 'applied': None})
    saved = stalled_reason({'status': 'approved', 'applied': 1})
    for text in (unsaved, saved):
        assert 'is recorded' not in text
        assert 'running right now' in text
        assert 'Another approval is not needed.' in text
    assert 'not yet saved into the document' in unsaved
    assert 'not yet independently checked' in saved


