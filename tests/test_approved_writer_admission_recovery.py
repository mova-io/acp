    payload = json.loads(job['payload'])
    with pytest.raises(handlers.FatalJobError):
        handlers._apply_approved_values({k:v for k,v in payload.items() if k != 'approved_binding'}, {})
    with store._db.cursor() as cur:
        store._db.execute(cur, 'UPDATE hitl_queue SET decision_version=decision_version+1 WHERE id=%s', (item_id,))
    with pytest.raises(handlers.FatalJobError): handlers._apply_approved_values(payload, {})


