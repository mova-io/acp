def test_worker_refuses_missing_binding_and_changes_after_admission(store, monkeypatch):
    import core, handlers
    monkeypatch.setattr(core, 'store', store)
    item_id = seed(store)
    with store._db.cursor() as cur: store._db.execute(cur, "UPDATE jobs SET status='done'")
    result = store.retry_approved_write(item_id)
