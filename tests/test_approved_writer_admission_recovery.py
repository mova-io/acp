def test_concurrent_retries_for_two_rows_share_one_file_writer(store):
    from concurrent.futures import ThreadPoolExecutor
    first = seed(store)
    second = store.enqueue_proposals(SID, FILE, '1.1.1', [{'locator':'word/document.xml#rId1','proposed_value':'Description'}])
    with store._db.cursor() as cur:
        store._db.execute(cur, 'UPDATE hitl_queue SET proposal_snapshot_ids=%s WHERE id=%s', ('["snapshot-2"]',second))
    store.complete_hitl_decision(second, 'approved', None, None, approved_values=['Description'], resolution=None, actor='reviewer', detail=None)
    with store._db.cursor() as cur: store._db.execute(cur,"UPDATE jobs SET status='done'")
    with ThreadPoolExecutor(max_workers=2) as pool:
        outcomes = list(pool.map(store.retry_approved_write,[first,second]))
    assert sum(r['accepted'] for r in outcomes) == 1
    assert [r['reason'] for r in outcomes if not r['accepted']] == [store.RETRY_WRITER_BUSY]
    assert len([j for j in writer_jobs(store) if j['status']=='queued']) == 1


