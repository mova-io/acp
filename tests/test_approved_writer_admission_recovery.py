@pytest.fixture
def store(monkeypatch, tmp_path):
    import store as store_module
    monkeypatch.setattr(store_module, '_SQLITE_PATH', tmp_path / 'recovery.db')
    return store_module.Store()


def seed(store, *, status='approved', value='Discharge instructions'):
    """The production shape: one 1.4.5 proposal, approved, `applied` never set."""
    store.init_scan_run(SID, 'drive', 1, '2026-09-17T00:00:00Z', 'rubric', 'hash')
    store.save_file_result(SID, {
        'file': FILE, 'engine': 'office', 'status': 'pass', 'score': 60, 'compliant': 0,
        'skipped_rules': 0, 'drive_file_id': 'd1',
        'issues': [{'ruleId': 'OCR_IMAGE_OF_TEXT', 'wcag': '1.4.5 Images of Text',
                    'severity': 'SERIOUS', 'detail': 'embedded image 1 contains readable text'}],
    }, '2026-09-17T00:00:00Z')
    store.record_remediation(SID, FILE, drive_write_url='http://d/1', blob_url='http://b/1', corrected_sha256='a'*64)
    item_id = store.enqueue_proposals(SID, FILE, '1.4.5', [
        {'locator': 'image 1', 'before': 'text baked into an image', 'proposed_value': value,
         'rationale': 'r', 'source': 'OCR'}], rule_name='Images of Text')
    with store._db.cursor() as cur:
        store._db.execute(cur, 'UPDATE hitl_queue SET proposal_snapshot_ids=%s WHERE id=%s',
                          (json.dumps(['immutable-proposal-1']), item_id))
    if status:
        # The production decision path, so the approval's OWN writer enqueue, decision-log line
        # and value binding are all real — a retry that only ever ran against a hand-built row
        # would prove nothing about the state this recovers.
        store.complete_hitl_decision(item_id, status, None, None, resolution=None,
                                     approved_values=[value] if status == 'approved' else None,
                                     actor='reviewer@example.com', detail=None)
    return item_id


def writer_jobs(store):
    with store._db.cursor() as cur:
        store._db.execute(cur, "SELECT id,type,payload,status FROM jobs "
                               "WHERE scan_id=%s AND type='apply_approved_values'", (SID,))
        return store._db.fetchall(cur)


def snapshot(store, item_id):
    """Everything about the row a recovery must not touch."""
    row = store.get_hitl_item(item_id)
    return {k: row.get(k) for k in (
        'status', 'applied', 'validated', 'decision_version', 'approved_value_sha256',
        'approved_source_revision', 'approved_proposal_snapshot_ids', 'reviewed_at',
        'last_decision_request_id', 'proposals', 'resolution', 'reviewer_note')}


def test_retry_enqueues_the_writer_and_creates_no_approval(store):
    item_id = seed(store)
    # The approval's own enqueue has already happened and (in production) already refused; drop
    # it so the state under test is the stranded one: approved, unapplied, nothing in flight.
    with store._db.cursor() as cur:
        store._db.execute(cur, "UPDATE jobs SET status='done' WHERE scan_id=%s", (SID,))
    before = snapshot(store, item_id)
    decisions_before = {d['id'] for d in store.list_decisions(scan_id=SID)}

    result = store.retry_approved_write(item_id, actor='reviewer@example.com')

    assert result['accepted'] is True and result['existing'] is False and result['reason'] is None
    queued = [j for j in writer_jobs(store) if j['status'] == 'queued']
    assert len(queued) == 1 and queued[0]['id'] == result['job_id']
    # The SAME payload a reviewer's own approval enqueues: the handler, and therefore every
    # downstream guard, runs unchanged.
    payload = json.loads(queued[0]['payload']) if isinstance(queued[0]['payload'], str) else queued[0]['payload']
    assert payload['scan_id'] == SID and payload['file'] == FILE
    assert payload['item_id'] == item_id
    assert payload['approved_binding'] == store.approved_write_binding(store.get_hitl_item(item_id))[0]

    # NOTHING about the review row moved. No new approval, no decision_version bump, not applied.
    assert snapshot(store, item_id) == before
    assert store.get_hitl_item(item_id)['status'] == 'approved'
    assert not store.get_hitl_item(item_id).get('applied')
    assert store.count_unapplied_approved_values(SID, FILE) > 0
    # EXACTLY ONE new audit line, and it is not a decision on the item: the `hitl.approved`
    # line belongs to the reviewer's original approval and no second one may appear.
    added = [d for d in store.list_decisions(scan_id=SID) if d['id'] not in decisions_before]
    assert [d['action'] for d in added] == ['apply.retry_requested']
    assert added[0]['actor'] == 'reviewer@example.com'
    assert 'no new approval was created' in added[0]['detail']
    assert len([d for d in store.list_decisions(scan_id=SID)
                if d['action'].startswith('hitl.')]) == 1


def test_retry_is_idempotent_and_never_races_a_second_writer(store):
    item_id = seed(store)
    with store._db.cursor() as cur:
        store._db.execute(cur, "UPDATE jobs SET status='done' WHERE scan_id=%s", (SID,))
    first = store.retry_approved_write(item_id)
    second = store.retry_approved_write(item_id)
    third = store.retry_approved_write(item_id)
    assert second == {'accepted': True, 'in_flight': True, 'status': 'queued', 'job_id': first['job_id'], 'existing': True, 'reason': None}
    assert third['existing'] is True
    assert len([j for j in writer_jobs(store) if j['status'] == 'queued']) == 1


def test_a_writer_already_in_flight_is_the_retry(store):
    """The approval's own job is still queued: returning it beats racing it over the same bytes."""
    item_id = seed(store)
    live = [j for j in writer_jobs(store) if j['status'] == 'queued']
    assert len(live) == 1, 'the approval must have enqueued a writer to begin with'
    result = store.retry_approved_write(item_id)
    assert result == {'accepted': True, 'in_flight': True, 'status': 'queued', 'job_id': live[0]['id'], 'existing': True, 'reason': None}
    assert len(writer_jobs(store)) == 1


